import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const srcRoot = join(root, "node_modules", "foliate-js");
const outRoot = join(root, "assets", "vendor");

const files = [
  ["pdfjs/pdf.min.mjs", join(root, "node_modules/pdfjs-dist/build/pdf.min.mjs")],
  ["pdfjs/pdf.worker.min.mjs", join(root, "node_modules/pdfjs-dist/build/pdf.worker.min.mjs")],
  ...[
    "view.js",
    "epubcfi.js",
    "progress.js",
    "overlayer.js",
    "text-walker.js",
    "epub.js",
    "comic-book.js",
    "fb2.js",
    "mobi.js",
    "fixed-layout.js",
    "paginator.js",
    "search.js",
    "tts.js",
    "vendor/zip.js",
    "vendor/fflate.js",
  ].map((rel) => [`foliate-js/${rel}`, join(srcRoot, rel)]),
];

const entries = [];
for (const [dest, from] of files) {
  const target = join(outRoot, `${dest}.bin`);
  mkdirSync(dirname(target), { recursive: true });
  writeFileSync(target, readFileSync(from));
  entries.push(`  ${JSON.stringify(dest)}: require(${JSON.stringify(`../../assets/vendor/${dest}.bin`)}) as number,`);
}

const manifest = `/* eslint-disable @typescript-eslint/no-require-imports */
/** Local PDF.js and foliate-js copies. Generated by scripts/sync-vendor.mjs. */
export const viewerAssets: Record<string, number> = {
${entries.join("\n")}
};
`;
writeFileSync(join(root, "src/reader/vendorManifest.ts"), manifest);
console.log(`copied ${files.length} vendor files`);
